export const ICON_NAMES = Object.freeze(Object.keys(ICONS));

/**
 * @param {string} name
 * @param {object} [o]
 * @param {number} [o.size=24]
 * @param {number} [o.stroke=2.25]   2 à 2.5 selon la taille
 * @param {string} [o.className]
 * @param {string} [o.label]         libellé accessible ; absent = décoratif
 */
export function icon(name, { size = 24, stroke = 2.25, className = '', label } = {}) {
  const body = ICONS[name];
  if (!body) throw new Error(`[icons] icône inconnue : ${name}`);
  const a11y = label ? `role="img" aria-label="${label}"` : 'aria-hidden="true" focusable="false"';
  return `<svg xmlns="http://www.w3.org/2000/svg" class="icon${className ? ' ' + className : ''}" width="${size}" height="${size}" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="${stroke}" stroke-linecap="round" stroke-linejoin="round" ${a11y}>${body}</svg>`;
}

/** Remplace chaque <i data-icon="nom" data-size="20" data-stroke="2"> par le SVG. */
export function hydrateIcons(root = globalThis.document) {
  if (!root) return;
  root.querySelectorAll('i[data-icon]').forEach((el) => {
    const { icon: name, size, stroke, label } = el.dataset;
    el.outerHTML = icon(name, {
      size: size ? Number(size) : undefined,
      stroke: stroke ? Number(stroke) : undefined,
      className: el.className,
      label,
    });
  });
}
